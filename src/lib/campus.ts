/**
 * Which building (and floor) a timetable room is in: `成306嵌入式系統實驗室` → 大成館, 3F.
 * Rooms are numbered floor-first (306 → 3F, 1012 → 10F).
 */
export function findRoom(room: string) {
  const m = room.trim().match(/^(\D+?)(\d{3,4})/);
  if (!m) return null;
  const building = BUILDINGS.find((b) => b.prefixes.includes(m[1]));
  if (!building) return null;
  const floor = `${m[2].length === 4 ? m[2].slice(0, 2) : m[2][0]}F`;
  return { building, floor, code: `${m[1]}${m[2]}` };
}
